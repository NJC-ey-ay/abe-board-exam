export function findFormulasByKeyword(query: string): KeywordFormula[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return keywordFormulas.filter(f =>
    f.keywords.some(k => k.toLowerCase().includes(q))
  );
}

